import { test, expect } from '@playwright/test';
test.skip(!process.env.E2E_SUPABASE, 'Requires an isolated local Supabase instance.');
test('a student creates a discipline and note, saves to the cloud and sees them on another device', async ({ page, browser }, testInfo) => {
  test.setTimeout(60000);
  const email = `student-${testInfo.project.name}-${Date.now()}@example.com`, password = 'test-password-123';
  await page.goto('/entrar');
  await page.getByRole('button', { name: 'Criar uma conta', exact: true }).click();
  await page.getByLabel('Seu nome', { exact: true }).fill('Estudante');
  await page.getByLabel('E-mail', { exact: true }).fill(email);
  await page.getByLabel('Senha', { exact: true }).fill(password);
  await page.getByLabel('Confirme sua senha', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Criar conta', exact: true }).click();
  await expect(page.getByText('Monte seu fichário em três passos')).toBeVisible();
  await page.goto('/subjects');
  await page.getByRole('button', { name: 'Nova disciplina', exact: true }).click();
  await page.getByLabel('Nome da disciplina', { exact: true }).fill('Cálculo aplicado');
  await page.getByRole('button', { name: 'Criar disciplina', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Cálculo aplicado', exact: true })).toBeVisible();
  await expect(page.getByText('Dados sincronizados', { exact: true })).toBeVisible({ timeout: 15000 });
  await page.goto('/records?new=1');
  await page.getByLabel('Título da página', { exact: true }).fill('Minha revisão de cálculo');
  await page.getByRole('textbox', { name: 'Conteúdo do caderno', exact: true }).fill('Ideias importantes para revisar antes da prova.');
  await page.getByRole('button', { name: 'Salvar trabalho', exact: true }).click();
  await expect(page.getByText('Dados sincronizados', { exact: true })).toBeVisible({ timeout: 15000 });
  await page.screenshot({ path: testInfo.outputPath('caderno.png'), fullPage: true });
  const context = await browser.newContext();
  try {
    const other = await context.newPage();
    await other.goto('/entrar');
    await other.getByLabel('E-mail', { exact: true }).fill(email);
    await other.getByLabel('Senha', { exact: true }).fill(password);
    await other.getByRole('button', { name: 'Entrar', exact: true }).click();
    await expect(other.getByRole('button', { name: 'Sair', exact: true })).toBeVisible();
    await expect(other.getByText('Dados sincronizados', { exact: true })).toBeVisible({ timeout: 15000 });
    await other.goto('/subjects');
    await expect(other.getByRole('heading', { name: 'Cálculo aplicado', exact: true })).toBeVisible();
    await other.goto('/records');
    await expect(other.getByText('Minha revisão de cálculo', { exact: true }).first()).toBeVisible();
  } finally { await context.close(); }
  await page.goto('/profile');
  await expect(page.getByRole('heading', { name: 'Conta e segurança' })).toBeVisible();
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Exportar todos os meus dados pessoais' }).click();
  expect((await download).suggestedFilename()).toContain('future-academy');
  await expect(page.getByText('Dados sincronizados', { exact: true })).toBeVisible({ timeout: 15000 });
  await page.getByRole('button', { name: 'Excluir minha conta', exact: true }).click();
  await page.getByLabel('Digite EXCLUIR para confirmar').fill('EXCLUIR');
  await page.getByRole('button', { name: 'Excluir definitivamente', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Entrar', exact: true })).toBeVisible({ timeout: 15000 });
});
