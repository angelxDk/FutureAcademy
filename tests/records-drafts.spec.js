import { it, expect, vi, beforeEach } from 'vitest';
import { mount } from '@vue/test-utils';
import { createPinia, setActivePinia } from 'pinia';
import { createRouter, createMemoryHistory } from 'vue-router';
vi.mock('../src/stores/useSyncStore', () => ({ useSyncStore: () => ({ persistState: vi.fn() }) }));
vi.mock('../src/composables/useDebouncedPersist', () => ({ useDebouncedPersist: () => vi.fn() }));
import RecordsSection from '../src/sections/RecordsSection.vue';
import { useRecordsStore } from '../src/stores/useRecordsStore';
import { useAppStore } from '../src/stores/useAppStore';
it('keeps drafts for multiple documents and restores the unsaved new page after saving another document', async () => {
  const pinia = createPinia(); setActivePinia(pinia);
  const records = useRecordsStore();
  records.draft = { form: { title: 'Nova ideia' }, html: '<p>Texto ainda não salvo</p>', editId: '' };
  records.records = [{ id: 'one', title: 'Aula 1', contentHtml: '<p>Original</p>', status: 'pendente' }, { id: 'two', title: 'Aula 2', contentHtml: '<p>Outra aula</p>', status: 'pendente' }];
  const router = createRouter({ history: createMemoryHistory(), routes: [{ path: '/records', name: 'records', component: RecordsSection }] });
  await router.push('/records');
  const stubs = Object.fromEntries(['VIcon','VBtn','VMenu','VList','VListItem','VForm','VRow','VCol','VTextField','VSelect','VDialog','VCard','VCardActions','NotebookEditor'].map(name => [name, true]));
  const wrapper = mount(RecordsSection, { global: { plugins: [pinia, router], stubs } });
  wrapper.vm.startRecordEdit('one');
  wrapper.vm.recordEditorHtml = '<p>Minha edição importante</p>';
  wrapper.vm.startRecordEdit('two');
  expect(records.drafts.one.html).toContain('Minha edição importante');
  expect(records.drafts.__new__.html).toContain('Texto ainda não salvo');
  wrapper.vm.restoreDraft('one');
  expect(wrapper.vm.recordEditorHtml).toContain('Minha edição importante');
  wrapper.vm.submitRecord();
  expect(records.records.find(r => r.id === 'one').contentHtml).toContain('Minha edição importante');
  expect(wrapper.vm.recordForm.title).toBe('Nova ideia');
  expect(wrapper.vm.recordEditorHtml).toContain('Texto ainda não salvo');
  clearTimeout(useAppStore().toastTimeout); wrapper.unmount();
});
